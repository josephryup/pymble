const dateSchema = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);

/**
 * Creating an invoice.
 *
 * Two fields deliberately absent:
 *
 *   • **invoice_number** — always generated by `ops_next_invoice_number` from
 *     the organisation prefix. It was accepted as an optional override, which
 *     bypassed the counter entirely; two invoices sharing a number is a tax
 *     problem, not a cosmetic one. A number is now assigned, never supplied.
 *   • **boq_id** — the BOQ link was answering "where did this invoice come
 *     from" badly, and was optional so nothing depended on it. The `source` /
 *     `source_id` pair replaces it in R4
 *     (docs/pymble-ops-payables-receivables-split-2026-08.md §4b). The column
 *     stays for now; nothing writes it.
 */
const createInvoiceSchema = z.object({
  client_name: z.string().trim().min(2, "Client name is required.").max(160),
  customer_id: z
    .string()
    .trim()
    .transform((value) => (value.length > 0 ? value : null))
    .pipe(z.string().uuid().nullable()),
  issued_at: dateSchema,
  site_id: z.string().uuid("Select a Pymble site."),
  subtotal: z.coerce.number().min(0, "Subtotal cannot be negative."),
  tpin: z.string().trim().max(80).default(""),
});

const invoiceIdSchema = z.object({
  id: z.string().uuid("Select an invoice."),
});

function field(formData: FormData, name: string) {
  const value = formData.get(name);
  return typeof value === "string" ? value : "";
}

function invoiceError(message: string): never {
  redirect(`/ops/invoices?error=${encodeURIComponent(safeOpsActionErrorMessage(message))}`);
}

function roundToTwo(value: number) {
  return Math.round((value + Number.EPSILON) * 100) / 100;
}

/**
 * Allocates the next invoice number atomically via the
 * `public.ops_next_invoice_number(prefix)` Postgres function. Numbers are
 * monotonic and gap-free per (prefix, year). Per ZRA requirements, a consumed
 * number that ends up cancelled or voided must remain on file — the function
 * does NOT recycle gaps.
 *
 * Called with the SERVICE client, not the cookie session client. Migration
 * 20260805091000 (audit finding S5) revoked EXECUTE from `authenticated`,
 * because a SECURITY DEFINER function reachable from any browser session via
 * /rest/v1/rpc/ lets any signed-in user burn invoice numbers. The revoke
 * assumed the server already called it as the service role; it did not, so
 * every invoice creation has failed with 42501 since that migration ran.
 * Calling as service_role is the side of that mismatch worth keeping — the
 * caller has already checked the role (canCreateInvoice) before getting here.
 */
async function nextInvoiceNumber(prefix: string) {
  const supabase = getOpsSupabaseServiceClient();
  const { data, error } = await supabase.rpc("ops_next_invoice_number", {
    p_prefix: prefix,
  });

  if (error) {
    throw error;
  }

  if (typeof data !== "string" || data.length === 0) {
    throw new Error("Invoice number generator returned an empty value.");
  }

  return data;
}

/**
 * When this invoice falls due.
 *
 * Stored on the invoice rather than looked up through the customer at read
 * time: the due date is printed on the copy the client holds, so it is a fact
 * about the invoice. Reading it live would silently re-date history — and
 * restate every past ageing report — the moment somebody renegotiated terms.
 *
 * Null when there is no customer to take terms from. Ageing treats an invoice
 * with no due date as "current" rather than guessing, because an invented
 * deadline is worse than an absent one: it produces a debtor chased for a date
 * nobody agreed.
 */
async function resolveInvoiceDueDate(customerId: string | null, issuedAt: string) {
  if (!customerId) {
    return null;
  }

  const supabase = await createOpsServerSessionClient();
  const { data, error } = await supabase
    .from("customers")
    .select("payment_terms_days")
    .eq("id", customerId)
    .maybeSingle<{ payment_terms_days: number }>();

  if (error || !data) {
    return null;
  }

  const due = new Date(`${issuedAt}T00:00:00Z`);
  due.setUTCDate(due.getUTCDate() + Number(data.payment_terms_days ?? 0));
  return due.toISOString().slice(0, 10);
}

export async function createInvoiceAction(formData: FormData) {
  const { profile } = await requireOpsUser();

  if (!canCreateInvoice(profile.role)) {
    invoiceError(
      "Only the Quantity Surveyor, Finance Manager, Accountant, and leadership can create invoices.",
    );
  }

  const parsed = createInvoiceSchema.safeParse({
    client_name: field(formData, "client_name"),
    customer_id: field(formData, "customer_id"),
    issued_at: field(formData, "issued_at"),
    site_id: field(formData, "site_id"),
    subtotal: field(formData, "subtotal"),
    tpin: field(formData, "tpin"),
  });

  if (!parsed.success) {
    invoiceError(parsed.error.issues[0]?.message ?? "Check the invoice details.");
  }

  const supabase = await createOpsServerSessionClient();
  const { data: organization, error: organizationError } = await supabase
    .from("organization_profile")
    .select("invoice_prefix, vat_rate")
    .eq("id", 1)
    .single<Pick<OrganizationProfile, "invoice_prefix" | "vat_rate">>();

  if (organizationError || !organization) {
    invoiceError(organizationError?.message ?? "Pymble organization profile was not found.");
  }

  // Always generated. See createInvoiceSchema for why there is no override.
  const invoiceNumber = await nextInvoiceNumber(organization.invoice_prefix);
  const vatAmount = roundToTwo(parsed.data.subtotal * Number(organization.vat_rate));
  const totalAmount = roundToTwo(parsed.data.subtotal + vatAmount);
  const dueDate = await resolveInvoiceDueDate(
    parsed.data.customer_id,
    parsed.data.issued_at,
  );

  const { data, error } = await supabase
    .from("invoices")
    .insert({
      client_name: parsed.data.client_name,
      created_by: profile.id,
      customer_id: parsed.data.customer_id,
      due_date: dueDate,
      invoice_number: invoiceNumber,
      issued_at: parsed.data.issued_at,
      site_id: parsed.data.site_id,
      status: "draft",
      subtotal: roundToTwo(parsed.data.subtotal),
      total_amount: totalAmount,
      tpin: parsed.data.tpin || null,
      vat_amount: vatAmount,
    })
    .select("id")
    .single<{ id: string }>();

  if (error || !data) {
    invoiceError(
      error
        ? error.code === "23505"
          ? "That invoice number already exists."
          : error.message
        : "The invoice could not be created.",
    );
  }

  await supabase.from("audit_events").insert({
    actor_user_id: profile.id,
    action: "invoice.created",
    entity_type: "invoice",
    entity_id: data.id,
    module_key: "invoices",
    source_table: "invoices",
    source_id: data.id,
    metadata: {
      due_date: dueDate,
      invoice_number: invoiceNumber,
      total_amount: totalAmount,
    },
  });

  revalidatePath("/ops");
  revalidatePath("/ops/invoices");
  redirect("/ops/invoices?created=invoice");
}

async function fetchInvoiceMutationTarget(
  invoiceId: string,
): Promise<(OpsInvoiceMutationTarget & { id: string; invoice_number: string }) | null> {
  const supabase = await createOpsServerSessionClient();
  const { data, error } = await supabase
    .from("invoices")
    .select("id, invoice_number, status, cancelled_at, archived_at, deleted_at")
    .eq("id", invoiceId)
    .maybeSingle<OpsInvoiceMutationTarget & { id: string; invoice_number: string }>();
  if (error) {
    throw error;
  }
  return data;
}

/**
 * Sending an invoice: recognise the revenue and the receivable.
 *
 * Narrowed to "sent" only. It used to take "paid" as well and post the cash
 * journal for the whole invoice — which, now that every payment posts per
 * receipt, would book the same money twice. Settling happens through
 * writeInvoiceReceipt, and the type stops that path being re-opened by
 * accident.
 */
async function updateInvoiceStatus(id: string, status: "sent", userId: string) {
  const supabase = await createOpsServerSessionClient();
  const timestampColumn = "sent_at";
  const { data, error } = await supabase
    .from("invoices")
    .update({
      [timestampColumn]: new Date().toISOString(),
      status,
    })
    .eq("id", id)
    .select("id")
    .maybeSingle<{ id: string }>();

  if (error || !data) {
    invoiceError(error?.message ?? "Invoice status could not be updated.");
  }

  await supabase.from("audit_events").insert({
    actor_user_id: userId,
    action: `invoice.${status}`,
    entity_type: "invoice",
    entity_id: data.id,
  });

  // Revenue recognition. Best-effort + idempotent — never blocks the send.
  await postInvoiceJournalSafe(data.id, "issued", userId);

  await notifyOpsWorkflowEvent({
    actorId: userId,
    actionNeededRoles: ["finance_manager", "accountant"],
    title: `Invoice ${status}`,
    body: `An invoice was marked ${status} and the matching ledger journal was posted.`,
    actionHref: "/ops/invoices",
    moduleKey: "invoices",
    sourceTable: "invoices",
    sourceId: data.id,
    eventKey: status,
    category: "info",
  });
}

export async function sendInvoiceAction(formData: FormData) {
  const { profile } = await requireOpsUser();

  const parsed = invoiceIdSchema.safeParse({ id: field(formData, "id") });

  if (!parsed.success) {
    invoiceError(parsed.error.issues[0]?.message ?? "Select an invoice.");
  }

  const invoice = await fetchInvoiceMutationTarget(parsed.data.id);
  if (!invoice) {
    invoiceError("Invoice was not found.");
  }
  if (!canSendInvoice(profile.role, invoice)) {
    invoiceError("Only Finance and leadership can send a draft invoice.");
  }

  await updateInvoiceStatus(parsed.data.id, "sent", profile.id);

  revalidatePath("/ops/invoices");
  redirect("/ops/invoices?updated=sent");
}

